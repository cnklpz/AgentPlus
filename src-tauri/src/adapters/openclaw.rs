//! OpenClaw (formerly Clawdbot / Moltbot): `~/.openclaw/openclaw.json` (JSON5) with custom
//! providers under `models.providers.<id>` (same shape as pi's models.json) and the default
//! model in `agents.defaults.model.primary` ("provider/model").
//!
//! The config schema is strict (an unknown key stops the gateway), so only documented keys
//! are ever added: provider display names live in the AgentPlus store, not in the file. The
//! file is written back as plain pretty JSON, so a file using JSON5-only syntax (comments,
//! unquoted keys, trailing commas…) is shown read-only.
//!
//! `~/.openclaw/agents/<id>/agent/models.json` is generated by OpenClaw and its
//! baseUrl / apiKey win over openclaw.json, so address / key changes are mirrored there.


