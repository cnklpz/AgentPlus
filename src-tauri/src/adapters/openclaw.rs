/// `~/.openclaw` (or `$OPENCLAW_STATE_DIR`, or the folder picked in AgentPlus).
pub fn default_dir() -> PathBuf {
    if let Some(r) = pimodels::test_root() {
        return r.join("openclaw");
    }
    if let Some(d) = super::dir_override(ID) {
        return d;
    }
    if let Some(d) = pimodels::env_var("OPENCLAW_STATE_DIR") {
        return crate::env::resolve_path(&d);
    }
    home().join(".openclaw")
}

fn config_path() -> PathBuf {
    if pimodels::test_root().is_none() && super::dir_override(ID).is_none() {
        if let Some(p) = pimodels::env_var("OPENCLAW_CONFIG_PATH") {
            return crate::env::resolve_path(&p);
        }
    }
    default_dir().join("openclaw.json")
}

fn fmt() -> Fmt {
    Fmt { agent: ID, flavor: Flavor::OpenClaw, path: config_path(), ptr: "/models/providers", auth: None, env_file: Some(default_dir().join(".env")) }
}

/// The generated per-agent model files (`agents/<id>/agent/models.json`).
fn generated() -> Vec<PathBuf> {
    let Ok(rd) = std::fs::read_dir(default_dir().join("agents")) else { return vec![] };
    let mut out: Vec<PathBuf> = rd.flatten().map(|e| e.path().join("agent").join("models.json")).filter(|p| p.is_file()).collect();
    out.sort();
    out
}

/// json5 hands numbers over as floats; turn whole ones back into integers.
fn integers(v: &mut Value) {
    match v {
        Value::Number(n) => {
            if let Some(f) = n.as_f64().filter(|f| n.is_f64() && f.fract() == 0.0 && f.abs() < 9.0e15) {
                *v = if f >= 0.0 { json!(f as u64) } else { json!(f as i64) };
            }
        }
        Value::Array(a) => a.iter_mut().for_each(integers),
        Value::Object(o) => o.values_mut().for_each(integers),
        _ => {}
    }
}

/// (config, meta, why it is read-only). A missing file reads as `{}`.
fn load() -> Result<(Value, TextMeta, Option<String>)> {
    let p = config_path();
    if !p.exists() {
        return Ok((json!({}), TextMeta::NEW, None));
    }
    let (text, meta) = read_text(&p)?;
    if let Ok(v) = serde_json::from_str::<Value>(&text) {
        return Ok((v, meta, None));
    }
    let mut v: Value = json5::from_str(&text).map_err(|e| anyhow!(tr!("{} 解析失败：{e}", "Failed to parse {}: {e}", display_path(&p))))?;
    integers(&mut v);
    Ok((v, meta, Some(l("openclaw.json 用了 JSON5 写法（注释、无引号的键、结尾逗号等），AgentPlus 写回会丢掉这些格式，已切换为只读。", "openclaw.json uses JSON5 syntax (comments, unquoted keys, trailing commas, etc.) that AgentPlus would lose on write. Switched to read-only.").into())))
}

fn has_include(v: &Value) -> bool {
    match v {
        Value::Object(o) => o.contains_key("$include") || o.values().any(has_include),
        Value::Array(a) => a.iter().any(has_include),
        _ => false,
    }
}

/// (primary, fallbacks) of `agents.defaults.model` (a "provider/model" string or `{ primary, fallbacks }`).
fn default_model(cfg: &Value) -> (Option<String>, Vec<String>) {
    match cfg.pointer("/agents/defaults/model") {
        Some(Value::String(s)) => (Some(s.clone()).filter(|s| !s.is_empty()), vec![]),
        Some(o @ Value::Object(_)) => (
            o.get("primary").and_then(|x| x.as_str()).map(String::from).filter(|s| !s.is_empty()),
            str_list(o.get("fallbacks")).unwrap_or_default(),
        ),
        _ => (None, vec![]),
    }
}

fn split_ref(r: &str) -> (&str, Option<&str>) {
    match r.split_once('/') {
        Some((p, m)) => (p, Some(m)),
        None => (r, None),
    }
}

pub fn detect() -> Install {
    let mut inst = Install::default();
    let npm = dirs::data_dir().map(|d| d.join("npm"));
    if let Some(pkg) = npm.as_ref().map(|d| d.join("node_modules").join("openclaw").join("package.json")) {
        if let Ok(text) = std::fs::read_to_string(pkg) {
            inst.installed = true;
            inst.version = serde_json::from_str::<Value>(&text).ok().and_then(|v| v.get("version").and_then(|x| x.as_str()).map(String::from));
            return inst;
        }
    }
    let shims = [npm.map(|d| d.join("openclaw.cmd")), dirs::data_local_dir().map(|d| d.join("pnpm").join("openclaw.cmd"))];
    inst.installed = shims.iter().flatten().any(|p| p.exists());
    inst
}

pub fn state(inst: &Install) -> AgentState {
    let f = fmt();
    let gen = generated();
    let mut files = vec![f.file()];
    files.extend(gen.iter().map(|p| display_path(p)));
    let mut st = AgentState {
        id: ID.into(),
        name: NAME.into(),
        installed: inst.installed,
        version: inst.version.clone(),
        running: inst.running,
        mode: "multi".into(),
        config_dir: default_dir().to_string_lossy().to_string(),
        files,
        current_provider: None,
        providers: vec![],
        catalog: None,
        catalog_file: None,
        settings: vec![],
        current: vec![],
        notes: vec![l("OpenClaw 的 gateway 会热加载配置，改动保存后即生效。", "The OpenClaw gateway hot-reloads its config, so changes take effect once saved.").into()],
        readonly: false,
        fixed_pending: false,
        fixed_prompt: false,
        restartable: false,
        model_fields: vec![],
    };
    if !gen.is_empty() {
        st.notes.push(l("agents/*/agent/models.json 是 OpenClaw 生成的，其中的 baseUrl / apiKey 优先于 openclaw.json；改地址或密钥时 AgentPlus 会一并同步。", "agents/*/agent/models.json is generated by OpenClaw and its baseUrl / apiKey override openclaw.json. AgentPlus updates them too when you change a base URL or API key.").into());
    }
    if !config_path().exists() {
        let h = home();
        if [".clawdbot", ".moltbot"].iter().any(|d| h.join(d).exists()) {
            st.notes.push(l("发现旧版 Clawdbot / Moltbot 的配置目录；运行一次 openclaw 会迁移到 ~/.openclaw。", "Found an old Clawdbot / Moltbot config folder. Run openclaw once to migrate it to ~/.openclaw.").into());
        }
    }
    let root = pimodels::load_store();
    let cfg = match load() {
        Ok((cfg, _, ro)) => {
            if let Some(why) = ro {
                st.readonly = true;
                st.notes.push(why);
            }
            cfg
        }
        Err(e) => {
            st.notes.push(e.to_string());
            st.readonly = true;
            return st;
        }
    };
    if has_include(&cfg) {
        st.notes.push(l("openclaw.json 用了 $include，被包含文件里的供应商这里看不到。", "openclaw.json uses $include; providers in included files are not shown here.").into());
    }
    if cfg.pointer("/models/mode").and_then(|x| x.as_str()) == Some("replace") {
        st.notes.push(l("models.mode = \"replace\"：只有这里列出的供应商可用，内置供应商被替换掉了。", "models.mode = \"replace\": only the providers listed here are available; the built-in providers are replaced.").into());
    }
    st.providers = f.providers(&cfg, &root, None);

    let (primary, fallbacks) = default_model(&cfg);
    let on: Vec<&Provider> = st.providers.iter().filter(|p| p.enabled).collect();
    let vis: usize = on.iter().map(|p| p.models.iter().filter(|m| m.visible).count()).sum();
    st.current = vec![
        Kv::text(l("自定义供应商", "Custom providers"), if on.is_empty() { l("无", "None").into() } else { on.iter().map(|p| p.name.as_str()).collect::<Vec<_>>().join(l("、", ", ")) }),
        Kv::mono(l("默认模型", "Default model"), primary.unwrap_or_else(|| "-".into())),
    ];
    if !fallbacks.is_empty() {
        st.current.push(Kv::mono(l("备用模型", "Fallback models"), fallbacks.join(", ")));
    }
    st.current.push(Kv::text(l("可见模型", "Visible models"), tr!("{vis} 个", "{vis}")));
    st.current.push(Kv::mono(l("配置文件", "Config file"), f.file()));
    st
}

pub fn provider_endpoint(id: &str) -> Result<Endpoint> {
    let (cfg, _, _) = load()?;
    fmt().endpoint(id, &cfg, &pimodels::load_store())
}

pub fn plan(ops: &[Op], dry_run: bool) -> Result<Plan> {
    let f = fmt();
    let (mut cfg, meta, readonly) = load()?;
    let cfg0 = cfg.clone();
    let mut root = pimodels::load_store();
    let mut none = None;
    let mut diff = Diff::default();
    let mut dirty = Dirty::default();
    let ef = f.file();

    for op in ops {
        if f.apply(op, &mut cfg, &mut root, &mut none, &mut diff, &mut dirty)? {
            continue;
        }
        match op {
            Op::SetCurrentProvider { .. } => return Err(anyhow!(l("OpenClaw 可以同时用多个供应商：按启用/停用管理，默认模型在 OpenClaw 里设置", "OpenClaw can use several providers at once: manage them by enabling/disabling, and set the default model in OpenClaw."))),
            Op::SetModelRoles { .. } => return Err(anyhow!(l("只有 Claude Code 需要分配模型角色", "Only Claude Code needs model roles."))),
            Op::SetSetting { key, .. } => return Err(anyhow!(tr!("OpenClaw 没有设置项 {key}", "OpenClaw has no setting {key}"))),
            Op::ImportProvider { .. } => unreachable!("resolved in adapters::plan"),
            _ => unreachable!("handled by pimodels"),
        }
    }

    // Don't leave the default / fallback models pointing at something that was just removed.
    if dirty.cfg {
        let gone = |r: &str| {
            let (p, m) = split_ref(r);
            f.has_model(&cfg0, p, m) && !f.has_model(&cfg, p, m)
        };
        let (primary, fallbacks) = default_model(&cfg);
        let primary_gone = primary.filter(|p| gone(p));
        let fallbacks_gone: Vec<bool> = fallbacks.iter().map(|r| gone(r)).collect();
        if let Some(p) = primary_gone {
            let model = cfg.pointer_mut("/agents/defaults").and_then(|d| d.as_object_mut()).unwrap();
            if model.get("model").map(|m| m.is_string()).unwrap_or(false) {
                model.remove("model");
            } else if let Some(o) = model.get_mut("model").and_then(|m| m.as_object_mut()) {
                o.remove("primary");
            }
            diff.push(&ef, tr!("- agents.defaults.model.primary（{p} 已移除，OpenClaw 会改用内置默认模型）", "- agents.defaults.model.primary ({p} was removed; OpenClaw will use its built-in default model)"), false);
        }
        if fallbacks_gone.contains(&true) {
            let mut keep = vec![];
            for (r, g) in fallbacks.iter().zip(&fallbacks_gone) {
                if *g {
                    diff.push(&ef, format!("agents.defaults.model.fallbacks - \"{r}\""), false);
                } else {
                    keep.push(json!(r));
                }
            }
            cfg["agents"]["defaults"]["model"]["fallbacks"] = Value::Array(keep);
        }
    }

    // Mirror address / key changes into the generated per-agent models.json files.
    let mut gen_out: Vec<(PathBuf, Value, TextMeta)> = vec![];
    if dirty.cfg {
        let now = f.providers_of(&cfg).cloned().unwrap_or_default();
        let old = f.providers_of(&cfg0).cloned().unwrap_or_default();
        let changes: Vec<(String, &'static str, Value)> = now
            .iter()
            .filter_map(|(id, def)| old.get(id).map(|o| (id, def, o)))
            .flat_map(|(id, def, o)| {
                ["baseUrl", "apiKey"].into_iter().filter_map(move |k| {
                    let v = def.get(k)?;
                    (o.get(k) != Some(v)).then(|| (id.clone(), k, v.clone()))
                })
            })
            .collect();
        if !changes.is_empty() {
            for path in generated() {
                let Ok((mut g, gm)) = read_json(&path) else { continue };
                let mut touched = false;
                for (id, k, v) in &changes {
                    if let Some(p) = g.pointer_mut(&crate::util::jptr(&["providers", id])).and_then(|p| p.as_object_mut()) {
                        if p.get(*k) != Some(v) {
                            p.insert(k.to_string(), v.clone());
                            let shown = if *k == "apiKey" { mask_key(v.as_str().unwrap_or("")) } else { v.as_str().unwrap_or("").to_string() };
                            diff.push(&display_path(&path), tr!("providers.{id}.{k} = {shown}（同步生成文件）", "providers.{id}.{k} = {shown} (synced to generated file)"), true);
                            touched = true;
                        }
                    }
                }
                if touched {
                    gen_out.push((path, g, gm));
                }
            }
        }
    }

    if dirty.cfg && readonly.is_some() {
        return Err(anyhow!(l("openclaw.json 用了 JSON5 写法，为避免丢失注释和格式不写入", "openclaw.json uses JSON5 syntax; not writing to avoid losing comments and formatting")));
    }
    let mut written = vec![];
    let mut backup_dir = None;
    if !dry_run && dirty.cfg {
        let mut targets = vec![config_path()];
        targets.extend(gen_out.iter().map(|g| g.0.clone()));
        backup_dir = Some(pimodels::backup_files(ID, &targets)?);
        if let Some(d) = config_path().parent() {
            std::fs::create_dir_all(d)?;
        }
        write_json(&config_path(), &cfg, meta)?;
        written.push(config_path());
        for (p, g, m) in &gen_out {
            write_json(p, g, *m)?;
            written.push(p.clone());
        }
    }
    if !dry_run && dirty.store {
        pimodels::save_store(&root)?;
    }
    Ok((diff, written, backup_dir))
}

